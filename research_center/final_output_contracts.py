def contract_for_command(command: str) -> FinalOutputContract | None:
    return FINAL_OUTPUT_CONTRACTS.get(command)


def prompt_rules_for_command(command: str) -> list[str]:
    contract = contract_for_command(command)
    if not contract:
        return []
    rules = [
        "請保留本指令專用的正式報告結構，不可改寫成泛用摘要。",
        "正式報告必須包含下列繁體中文章節名稱，允許加上編號，但不得省略核心章節：",
        "下列章節必須獨立成章，不可只把內容合併到其他章節；若資料不足，仍須保留章節並明確寫出資料缺口、反證與後續驗證方式。",
    ]
    rules.extend(f"- {section}" for section in contract.sections)
    if contract.content_terms:
        rules.append("正式報告必須明確出現下列評分、排名或估值關鍵詞：")
        rules.extend(f"- {term}" for term in contract.content_terms)
    if command == "research":
        rules.extend(
            [
                "請逐字建立「## AI 最終推薦買入評分」「## AI 最終財務與題材評分」「## AI 最終飆股基因評分」「## AI 最終價值重估評分」「## AI 評分細項拆解」「## 合理股價與目標價區間」「## 獲利預估與三情境推演」「## 題材水分與財報裂縫」「## 潛在催化因素」「## 市場資金輪動與題材熱度」「## 策略適配初判」等章節；不得只放在摘要表或合併到其他段落。",
                "每一個 AI 最終評分章節都必須包含細項分數拆解表，至少列出：評分細項、分數、權重或重要性、加分理由、扣分理由、信心程度。",
                "合理股價與目標價區間必須說明估算邏輯、樂觀/中性/保守情境、上修條件、下修條件；若資料不足，仍須給出可追蹤的估值框架與資料缺口，不可整段省略。",
                "深度版研究報告不可只保留本地量化評分；必須重新產出 AI 細項評分、獲利預估、題材水分、財報裂縫、催化因素、資金輪動與策略適配。",
            ]
        )
    if command == "value_scan":
        rules.extend(
            [
                "必須說明每個候選股的舊市場標籤、新市場標籤、重估證據、反證、資料缺口與後續研究優先度。",
                "若候選股未入選或分數偏低，仍須用繁體中文說明原因，不可只列代號或內部欄位。",
            ]
        )
    if command == "macro":
        rules.append("宏觀報告必須保留完整框架，不可只寫台股摘要；全球市場、央行、匯率、能源、信用風險、美股科技股與台股族群輪動都要明確評估。")
    if command == "theme":
        rules.extend(
            [
                "題材報告必須區分核心受惠、次受惠、觀察名單與不應納入公司，並說明資金流、價值重估可能與三情境推演。",
                "請逐字建立「## 全球需求變化」「## 主要大廠資本支出方向」「## 資金流入情況」「## 可能被價值重估的公司」「## 樂觀、基準與悲觀情境推演」「## 資料缺口」等章節；不得只用「全球產業趨勢」「目前題材位階」「後續觀察指標」等近義標題取代。",
            ]
        )
    if command == "theme_flow":
        rules.append("若資料過少或關聯股過少，必須在「資料過少警示與缺口」明確說明，不可假裝資金流已被充分驗證。")
    if command == "theme_radar":
        rules.append("題材雷達必須保留題材排行、族群排行、子族群排行、命中公司、題材脈絡、供應鏈輪廓與來源對照，不可只輸出摘要。")
    if command == "sector_strength":
        rules.append("產業強弱報告必須明確回答資金是否集中、集中在哪些族群、代表股與排除股是誰，以及反證與後續觀察條件。")
    rules.extend(
        [
            "所有結論必須保留來源引用、反證、風險、資料缺口、信心限制與後續驗證條件。",
            "不要輸出看不懂的英文參數名、內部欄位名或亂碼。",
        ]
    )
    return rules
