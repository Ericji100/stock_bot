"""One reader-facing evidence policy, shared by report and JSON workflows."""
from pathlib import Path


def reader_quality_rules(command: str | None = None) -> str:
    path = Path(__file__).resolve().parents[1] / "prompt/rules/reader_quality_rules.md"
    full, brief = path.read_text(encoding="utf-8-sig").split('## 短評用精簡規則', 1)
    rules = ('## 讀者效用與證據紀律\n' + brief.strip()) if command == 'radar' else full.strip()
    if command == 'radar':
        return rules + '\n發布、事件與數據日期分開；技術訊號日可能早於報告日，不可改寫為當日新訊號。官方入口網址僅是查詢線索，具體公司主張須有正文並核對代號。區分事實、推論與預測；保留具現實基礎的想像力，列驗證與失效條件。資料缺漏不等於公司表現差。'
    return rules + ('\n\n## 日期、公司與證據核對\n'
        '發布、更新、事件、數據期間、取得時間分開，未知不補造。官方入口網址僅是查詢線索；正文與數值須核對公司、期間。'
        '跨國市場必須核對資料取得時刻與市場時區；台灣凌晨的同日美股日線可能仍是盤中快照，不能當正式收盤。海外投票日不代表投票已結束或結果已確定；沒有結果證據就列進行中／待確認。'
        '代號、名稱、產品、客戶與曝險逐項核對，弱關聯只作候選。區分事實、推論、預測並核對反證；缺資料不等於公司差。'
        '同一數字在敘述、表格與公式必須一致；年度預測逐月／逐季加總不可漏期，資料缺期就明說而非假設為零。'
        '月營收的萬元、千萬元、億元須與全年加總相符；預測全年結果的最終驗證日不可早於該年度結束與財報可得日，提前觀察只能列領先指標。'
        '行情只涵蓋部分公司時，不可把該樣本漲跌延伸到無行情的公司。上漲家數、比例與新高家數分開比較；驗證與失效條件須與假說方向一致。'
        '不同增幅若非單純尾數進位，不可稱四捨五入；未見營收貢獻不等於證明公司蹭題材。公司簡稱差異與確定錯配分開。'
        '來源優先閱讀數不等於實際送入數；只可引用入模稽核的實際清單，無成功請求證據時不能宣稱全部已分析。'
        '比較均線高低先核對實際數值，不可前文低於、後文改寫高於。每股盈餘情境若同列營收、匯率、淨利率與股數，須以營收乘匯率乘淨利率除股數回算；純假設與反推值須明示。'
        '本益成長比使用每股盈餘成長率，不以營收成長率冒充；若只算營收成長相對倍數，應另名並揭露限制。毛利、營業利益是金額，毛利率、營益率是百分比，不能混寫。'
        '流動比率與速動比率分開，不把其中一項警示改寫成另一項不足。媒體數值與實際取得的官方數值衝突時，以公司、日期與口徑一致的官方數據優先並列差異。'
        '保留具現實基礎的想像力，列假設、時間、觸發與失效條件；本地檢查不保證語意正確。'
        '有具體預測的長報告列「預測追蹤」表：標的、假設、觀察截止日（西元年月日）、驗證條件、失效條件、來源。新聞與短評不強制長表。')
